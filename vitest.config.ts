/* ============================================================
 * Vitest 配置
 * ------------------------------------------------------------
 * 这里只做一件事：把超时从默认 5s 放宽到 20s。
 *
 * 原因不是「测试写得太慢」，而是**迁移的物理耗时**：
 * app/migrations 现在有 36 个文件，executor 对每个文件单独 BEGIN/COMMIT，
 * Windows 上一次提交就是一次真实 fsync，实测单线程跑完全量迁移就要约 4 秒。
 * 单独跑某个测试文件时完全够用（约 1 秒），但 `npm test` 会并发起满 28 个
 * 文件，IO 争用下同一个断言就能从 4 秒涨到 5 秒以上 —— 表现为「同一批测试
 * 每次失败的不是同一条」的随机红。
 *
 * 不要试图用「把迁移合并成一个大事务」来换时间：现在逐文件提交是为了
 * 单个迁移失败时能精确回滚、并且已应用的能落进 _migrations，
 * 合成一个大事务会让「重跑一次继续往下走」这个性质消失。
 * ============================================================ */
import { defineConfig } from 'vitest/config';

export default defineConfig({
  test: {
    testTimeout: 20000,
    hookTimeout: 20000,
    // 迁移类测试都在各自临时目录里建库，互不影响，并发不需要降
    pool: 'forks'
  }
});

/* ============================================================
 * 公开站 SSR 展示格式化
 * ------------------------------------------------------------
 * 数据库里的 date 存的是 ISO 时间戳（2026-10-05T04:15:28.502Z），
 * 直接渲染进卡片 / 文章头会显示成一长串机器格式。
 * 这里统一成 YYYY-MM-DD；已经是别的格式（含「2026年10月5日 …」）
 * 的值原样返回，避免二次格式化出错。
 * ============================================================ */

/** 把 ISO / 带前缀的时间串规整为 YYYY-MM-DD；无法识别时原样返回。 */
export function formatDate(value: unknown): string {
  const raw = String(value ?? '').trim();
  const m = /^(\d{4}-\d{2}-\d{2})/.exec(raw);
  return m ? m[1] : raw;
}
